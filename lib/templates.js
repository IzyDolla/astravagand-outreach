function steps(t) {
  return [
    { name: 'Mail 1', wait: 0, thread: false, subject: t.subject,
      body: `{Anrede},\n\n${t.pain}\n\n${t.offer}\n\n${t.ask}\n\nBeste Grüße\n{Absender}` },
    { name: 'Follow-up 1', wait: 3, thread: true, subject: '',
      body: `{Anrede},\n\nkurz nachgehakt: ${t.follow}\n\nFalls das ein Thema ist, schicke ich Ihnen gern ein kurzes Beispiel, wie das für {Firma} aussehen könnte – zwei Minuten zum Anschauen.\n\nBeste Grüße\n{Absender}` },
    { name: 'Follow-up 2', wait: 5, thread: true, subject: '',
      body: `{Anrede},\n\nich möchte nicht aufdringlich sein, daher ist das meine letzte Nachricht.\n\nFalls ${t.topic} für {Firma} später einmal Thema wird, antworten Sie einfach auf diese Mail – ich melde mich dann gern.\n\nAlles Gute\n{Absender}` }
  ];
}
const forCategory = catKey => IND.find(t => t.cats.includes(catKey)) || IND.find(t => t.key === 'allgemein');
const templateName = t => `${t.name} – 3 Schritte`;
const all = ws => IND.map(t => ({ ws_id: ws, type: 'seq', name: templateName(t), subject: '', body: '', steps: steps(t) }));

module.exports = { IND, steps, forCategory, templateName, all };
